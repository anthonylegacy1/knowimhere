export interface Resource {
  id: string;
  name: string;
  category: CategoryId;
  tags: CategoryId[];
  organization: string;
  summary: string;
  description: string;
  distanceMiles: number;
  when: When;
  whenLabel: string;
  cost: "Free" | "Low cost" | "Varies";
  location: string;
  neighborhood: string;
  accessibility: string[];
  transportation: string[];
  transitFriendly: boolean;
  walkable: boolean;
  seniorFriendly: boolean;
  youthFriendly: boolean;
  isOfficialResource?: boolean;
  /** Shown on the card for real (non-demonstration) resources, e.g. "Verified community resource". */
  sourceLabel?: string;
  /** Extra verified actions, e.g. a schedule or programme website. Always external. */
  links?: { label: string; href: string }[];
  /** e.g. "Ages 14–18" — shown on the card when the program is age-specific. */
  ageLabel?: string;
  /** Whether a listing is built for an age group or simply useful to them. */
  audience?: "senior-specific" | "youth-specific" | "general";
  lifeStages?: LifeStage[];
  nextStep: string;
}

